    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        String nama  = txtNama.getText().trim();
        String telp  = txtTelp.getText().trim();
        String email = txtEmail.getText().trim();
        String pass  = new String(txtPassword.getPassword());
        String role  = cbRole.getSelectedItem().toString();

        if (Validator.isKosong(nama, telp, email, pass)) {
            JOptionPane.showMessageDialog(this, "Semua field wajib diisi!");
            return;
        }
        if (!Validator.emailValid(email)) {
            JOptionPane.showMessageDialog(this, "Format email tidak valid.");
            return;
        }
        if (!Validator.teleponValid(telp)) {
            JOptionPane.showMessageDialog(this, "Nomor telepon harus valid (contoh: 08123456789).");
            return;
        }
        if (!Validator.passwordValid(pass)) {
            JOptionPane.showMessageDialog(this, "Password minimal 8 karakter dan harus mengandung huruf & angka.");
            return;
        }
        
        String[] extra;
        switch (role) {
            case "Pelanggan" -> extra = new String[] { "Samarinda" }; 
            case "Driver"    -> extra = new String[] { "Honda", "KT 1234 XX", "Motor", "Aktif" }; 
            default          -> extra = new String[] { "" };
        }

        try {
            // 5. Simpan ke database lewat controller
            userController.tambahUser(nama, telp, email, pass, role, extra);

            JOptionPane.showMessageDialog(this, "User baru berhasil ditambahkan!");
            this.dispose(); // Tutup form tambah data

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Gagal menambah user:\n" + ex.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

