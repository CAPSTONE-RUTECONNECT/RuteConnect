    private void loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginActionPerformed
        // TODO add your handling code here:
        String email = txtEmail.getText().trim();
        String password = new String(txtPassword.getPassword());
        
        AuthService.LoginResult result = AuthService.login(email, password);
        
        switch(result) {
            case BERHASIL -> {
                JOptionPane.showMessageDialog(this, "Login berhasil. Selamat datang, " + util.Session.nama + "!", "Login Sukses", JOptionPane.INFORMATION_MESSAGE);
                String role = util.Session.role != null ? util.Session.role.toLowerCase() : "";
                switch (role) {
                    case "pelanggan" -> {
                        java.awt.EventQueue.invokeLater(() -> new MenuPelangganForm().setVisible(true));
                        this.dispose();
                    }
                    case "driver" -> {
                        //taruh menu driver
                    }
                    case "admin" -> {
                        //taruh menu driver
                    }
                    default -> {
                        JOptionPane.showMessageDialog(this, "Role pengguna tidak valid.", "Peringatan", JOptionPane.WARNING_MESSAGE);
                        return;
                    }
                }
                this.dispose();
                break;
            }
            case INPUT_KOSONG -> {
                JOptionPane.showMessageDialog(this, "Input belum lengkap.", "Peringatan", JOptionPane.WARNING_MESSAGE);
            }
            case ERROR -> {
                JOptionPane.showMessageDialog(this, "Terjadi keslahan pada database.", "Peringatan", JOptionPane.ERROR_MESSAGE);
            }
            default -> {
                JOptionPane.showMessageDialog(this, "Email atau password salah.", "Login Gagal", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_loginActionPerformed

