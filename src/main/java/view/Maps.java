    public Maps() {
        initComponents();
        getContentPane().setPreferredSize(new java.awt.Dimension(390, 844));
        pack();
        setResizable(false);
        setLocationRelativeTo(null);
        
        txtStatus.setText("Klik 'Buka Peta' untuk memilih lokasi jemput dan tujuan.");
        
        // yang terjadi saat peta mengirim hasil rute
        peta = new PetaServer(h -> {
            txtJemput.setText(h.namaJemput());
            txtTujuan.setText(h.namaTujuan());
            txtJarak.setText(String.valueOf(h.km()));
            txtWaktu.setText(String.valueOf(h.menit()));
            txtStatus.setText("Rute berhasil diterima dari peta.");
        });

        try {
            peta.mulai();
        } catch (IOException e) {
            txtStatus.setText("Server peta gagal jalan: " + e.getMessage());
        }

        addWindowListener(new java.awt.event.WindowAdapter() {
            @Override public void windowClosing(java.awt.event.WindowEvent e) {
                peta.berhenti();
            }
        });
    }

