    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        String nama = txtNama.getText().trim();
        String telp = txtTelp.getText().trim();
        String email = txtEmail.getText().trim();

        // Validasi sederhana
        if (nama.isEmpty() || email.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Nama dan email tidak boleh kosong.");
            return;
        }
        if (!email.matches("^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Format email tidak valid.");
            return;
        }

        try {
            userController.updateUser(idUser, nama, telp, email, null);

            javax.swing.JOptionPane.showMessageDialog(this, "Data user berhasil diubah.");
            this.dispose();

        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal mengubah data:\n" + ex.getMessage(),
                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

