    private static boolean isAktif(model.Pesanan p) {
        String s = p.getStatusPesanan();
        return model.Pesanan.MENUNGGU.equals(s) || model.Pesanan.DITERIMA.equals(s)
            || model.Pesanan.DIPROSES.equals(s) || model.Pesanan.DALAM_PERJALANAN.equals(s);
    }

    private static int indeksTahap(String s) {
        if (model.Pesanan.DITERIMA.equals(s)) return 1;
        if (model.Pesanan.DIPROSES.equals(s)) return 2;
        if (model.Pesanan.DALAM_PERJALANAN.equals(s)) return 3;
        if (model.Pesanan.SELESAI.equals(s)) return 4;
        return 0;
    }

    private void muatData() {
        if (controller.Session.userId <= 0) return;
        java.util.List<model.Pesanan> semua =
                new dao.PesananDao().findByPelanggan(controller.Session.userId, "Semua");

        model.Pesanan aktif = null, terakhir = null;
        for (model.Pesanan p : semua) {
            if (isAktif(p)) {
                if (aktif == null) aktif = p;
            } else if (terakhir == null) {
                terakhir = p;
            }
        }
        pesananAktif = aktif;
        model.Pesanan tampil = aktif != null ? aktif : (semua.isEmpty() ? null : semua.get(0));

        // kartu atas
        if (tampil != null) {
            isiKartu(tampil, jLabel17, jLabel18, jLabel20, jLabel21);
            jLabel26.setText((Math.round(tampil.getJarakKm() * 10) / 10.0) + " Km");
        } else {
            jLabel17.setText("Belum ada pesanan");
            jLabel18.setText("Pesanan baru akan muncul di sini");
            jLabel20.setText("-");
            jLabel21.setText("-");
            jLabel26.setText("-");
        }

        isiProgress(tampil);

        // tombol batal: hanya aktif kalau belum dijemput
        boolean bisaBatal = aktif != null && aktif.bisaDibatalkan();
        jButton1.setEnabled(bisaBatal);
        jButton1.setToolTipText(aktif != null && !bisaBatal
                ? "Pesanan sudah dijemput, tidak dapat dibatalkan" : null);

        // kartu bawah (aktivitas terakhir)
        boolean tampilBawah = terakhir != null && terakhir != tampil;
        jLabel16.setVisible(tampilBawah);
        panelPesanProses.setVisible(tampilBawah);
        if (tampilBawah) isiKartu(terakhir, jLabel7, jLabel8, jLabel10, jLabel11);

        // tab semua riwayat
        DefaultTableModel m = (DefaultTableModel) tblSemuaRiwayat.getModel();
        m.setRowCount(0);
        for (model.Pesanan p : semua) {
            m.addRow(new Object[]{p.getPesananId(), p.getNamaLayanan(),
                    controller.Fmt.rupiah(p.getTotalBiaya()), p.getStatusPesanan()});
        }
    }

    private void isiKartu(model.Pesanan p, JLabel nama, JLabel sub, JLabel jemput, JLabel tujuan) {
        nama.setText(p.getNamaLayanan() + " (#" + p.getPesananId() + ")");
        sub.setText(p.getJenisPesanan() + " • " + p.getStatusPesanan());
        jemput.setText(htmlPotong(p.getLokasiJemput(), 70));
        jemput.setToolTipText(p.getLokasiJemput());
        tujuan.setText(htmlPotong(p.getLokasiTujuan(), 70));
        tujuan.setToolTipText(p.getLokasiTujuan());
    }

    private void isiProgress(model.Pesanan p) {
        DefaultTableModel m = (DefaultTableModel) jTable1.getModel();
        m.setRowCount(0);
        if (p == null) {
            tahapAktif = -1;
            return;
        }
        if (model.Pesanan.DIBATALKAN.equals(p.getStatusPesanan())) {
            tahapAktif = -1;
            m.addRow(new Object[]{"✖",
                "<html><b>Pesanan Dibatalkan</b><br><small>"
                    + esc(p.getAlasanBatal() != null ? p.getAlasanBatal() : "-") + "</small>", ""});
            return;
        }
        // Selesai -> semua tahap dianggap sudah lewat
        tahapAktif = model.Pesanan.SELESAI.equals(p.getStatusPesanan()) ? 5 : indeksTahap(p.getStatusPesanan());
        boolean dok = p instanceof model.Dokumen;

        String[] judul = {
            "Pesanan Dibuat",
            "Diterima Driver",
            "Menuju Lokasi Jemput",
            dok ? "Dokumen Diambil, Menuju Tujuan" : "Sudah Dijemput, Menuju Tujuan",
            "Pesanan Selesai"
        };
        String[] ket = {
            "Menunggu driver menerima pesanan",
            p.getNamaDriver() != null ? "Driver: " + p.getNamaDriver() : "-",
            potong(p.getLokasiJemput(), 40),
            potong(p.getLokasiTujuan(), 40),
            "Terima kasih telah menggunakan RuteConnect"
        };
        for (int i = 0; i < judul.length; i++) {
            String ikon = i < tahapAktif ? "✔" : i == tahapAktif ? "➜" : "●";
            String st = i < tahapAktif ? "Selesai" : i == tahapAktif ? "Sekarang" : "";
            m.addRow(new Object[]{ikon,
                "<html><b>" + esc(judul[i]) + "</b><br><small>" + esc(ket[i]) + "</small>", st});
        }
    }

    // pembatalan oleh pelanggan
    private void batalkanPesanan() {
        if (pesananAktif == null) {
            JOptionPane.showMessageDialog(this, "Tidak ada pesanan aktif.");
            return;
        }
        // cek ulang ke database
        model.Pesanan terbaru = new dao.PesananDao().findById(pesananAktif.getPesananId());
        if (terbaru == null || !terbaru.bisaDibatalkan()) {
            JOptionPane.showMessageDialog(this,
                    "Pesanan sudah dijemput driver dan tidak dapat dibatalkan.",
                    "Tidak Bisa Dibatalkan", JOptionPane.WARNING_MESSAGE);
            muatData();
            return;
        }

        String[] daftarAlasan = {
            "Salah memasukkan alamat / detail pesanan",
            "Driver terlalu jauh / tidak bergerak",
            "Waktu tunggu terlalu lama",
            "Berubah pikiran",
            "Driver meminta pembatalan"
        };
        JComboBox<String> cmb = new JComboBox<>(daftarAlasan);
        cmb.setSelectedIndex(-1);

        JPanel panel = new JPanel(new BorderLayout(5, 10));
        panel.add(new JLabel("Pilih alasan pembatalan pesanan:"), BorderLayout.NORTH);
        panel.add(cmb, BorderLayout.CENTER);

        int pilihan = JOptionPane.showConfirmDialog(this, panel, "Batalkan Pesanan",
                JOptionPane.OK_CANCEL_OPTION, JOptionPane.QUESTION_MESSAGE);
        if (pilihan != JOptionPane.OK_OPTION) return;

        String alasan = (String) cmb.getSelectedItem();
        if (alasan == null) {
            JOptionPane.showMessageDialog(this, "Silakan pilih alasan pembatalan terlebih dahulu.");
            return;
        }

        int yakin = JOptionPane.showConfirmDialog(this,
                "Alasan pembatalan:\n" + alasan + "\n\nApakah Anda yakin ingin membatalkan pesanan ini?",
                "Konfirmasi Pembatalan", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if (yakin != JOptionPane.YES_OPTION) return;

        service.Hasil h = new service.PesananService()
                .batalkanOlehCustomer(terbaru.getPesananId(), alasan);
        controller.Session.refreshSaldo();
        JOptionPane.showMessageDialog(this, h.getPesan(),
                h.isSukses() ? "Berhasil" : "Gagal",
                h.isSukses() ? JOptionPane.INFORMATION_MESSAGE : JOptionPane.ERROR_MESSAGE);
        muatData();
    }
    
